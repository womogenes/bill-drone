"""
The compute benchmark's replay (drone/main/bench_flight.c, make bench): a flight recording's sensor data as a C table, drone/main/bench_replay.h (not committed; recordings stay on R2). Each tick: the IMU as recorded (body order, counts), the barometer (mm, INT32_MIN without a reading), and the Kalman filter's velocity (mm/s north, west, up), position (cm north, west) and height (mm), from which the benchmark makes GPS solutions; and the tick the flip first ran, where the benchmark starts its own.
uv run tools/bench_replay.py RECORDING OUTPUT (RECORDING without .bin/.jsonl)
"""

import json
import struct
import sys
from pathlib import Path

# drone/main/flight_rt.c Record, by field index in its sample_format.
RAW, BARO, GUARD, EKF_VELOCITY, EKF_POSITION, EKF_HEIGHT, FLAGS = 2, 38, 39, 43, 46, 48, 20


def main():
    recording, output = Path(sys.argv[1]), Path(sys.argv[2])
    meta = next(entry for entry in map(json.loads, recording.with_suffix(".jsonl").read_text().splitlines()) if entry.get("type") == "metadata")
    form = "<" + meta["sample_format"].lstrip("<")
    data = recording.with_suffix(".bin").read_bytes()
    records = []
    offset = 0
    while offset + 12 <= len(data):
        _, _, count, size = struct.unpack_from("<4sIHH", data, offset)
        offset += 12
        for _ in range(count):
            records.append(struct.unpack_from(form, data, offset))
            offset += size
    records = [r for r in records if r[FLAGS] & 1]
    burst = next((i for i, r in enumerate(records) if r[GUARD] >> 6 & 3), len(records) // 2)
    lines = [
        f"// Generated by tools/bench_replay.py from {recording.name}: its {len(records)} armed ticks.",
        "#include <stdint.h>",
        "typedef struct {",
        "    int16_t raw[7];",
        "    int32_t baro_mm;",
        "    int16_t velocity[3], position[2], height;",
        "} ReplayTick;",
        f"#define REPLAY_TICKS {len(records)}",
        f"#define REPLAY_BURST {burst}",
        "static const ReplayTick replay[REPLAY_TICKS] = {",
    ]
    for r in records:
        raw = ",".join(str(v) for v in r[RAW:RAW + 7])
        baro = "INT32_MIN" if r[BARO] == -2**31 else str(r[BARO])
        velocity = ",".join(str(v) for v in r[EKF_VELOCITY:EKF_VELOCITY + 3])
        position = ",".join(str(v) for v in r[EKF_POSITION:EKF_POSITION + 2])
        lines.append(f"    {{{{{raw}}},{baro},{{{velocity}}},{{{position}}},{r[EKF_HEIGHT]}}},")
    lines.append("};")
    output.write_text("\n".join(lines) + "\n")
    print(f"{output}: {len(records)} ticks, the burst at {burst}")


if __name__ == "__main__":
    main()
